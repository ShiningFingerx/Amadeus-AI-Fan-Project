// scripts/generate-lore-data.js

const fs = require('fs');
const path = require('path');

const soundsDir = path.join(__dirname, '..', 'public', 'sounds', 'lore');
const textsDir = path.join(__dirname, '..', 'public', 'texts', 'lore');
const outputFilePath = path.join(__dirname, '..', 'src', 'data', 'loreAudio.ts');

console.log('Starting lore data generation...');
console.log(`Reading sounds from: ${soundsDir}`);
console.log(`Reading texts from: ${textsDir}`);

// Ensure directories exist
if (!fs.existsSync(soundsDir)) {
    console.log(`Sounds directory not found. Creating: ${soundsDir}`);
    fs.mkdirSync(soundsDir, { recursive: true });
}
if (!fs.existsSync(textsDir)) {
    console.log(`Texts directory not found. Creating: ${textsDir}`);
    fs.mkdirSync(textsDir, { recursive: true });
}


try {
    const soundFiles = fs.readdirSync(soundsDir).filter(file => file.endsWith('.ogg'));
    
    if (soundFiles.length === 0) {
        console.warn('No .ogg files found in public/sounds/lore/. The generated file will be empty.');
    } else {
        console.log(`Found ${soundFiles.length} sound files.`);
    }

    const loreAudioData = [];

    for (const soundFile of soundFiles) {
        const baseName = path.basename(soundFile, '.ogg');
        const textFilePath = path.join(textsDir, `${baseName}.txt`);

        let textContent = '';
        try {
            // Read the text file content, expecting UTF-8
            textContent = fs.readFileSync(textFilePath, 'utf8').trim().replace(/`/g, "'"); // Sanitize backticks
        } catch (error) {
            console.warn(`Warning: Could not find or read matching text file for ${soundFile}. Text will be empty.`);
        }

        loreAudioData.push({
            id: baseName,
            text: textContent,
            keywords: [] // Keywords are left empty as they cannot be auto-generated.
        });
    }
    
    // Sort by ID to maintain a consistent order
    loreAudioData.sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true, sensitivity: 'base' }));

    const tsContent = `// This file is auto-generated by 'npm run generate-lore'. Do not edit manually.
// It contains the mapping of lore audio files to their Japanese transcripts.

import type { LoreAudio } from '../types';

export const loreAudioData: LoreAudio[] = ${JSON.stringify(loreAudioData, null, 4)};
`;

    fs.writeFileSync(outputFilePath, tsContent, 'utf8');
    console.log(`Lore data generated successfully! ${loreAudioData.length} entries written to ${outputFilePath}`);

} catch (error) {
    console.error('An error occurred during lore data generation:', error);
    process.exit(1);
}
